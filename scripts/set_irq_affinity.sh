declare -r TFW_NETDEV_PATH="/sys/class/net/"
declare -r CPUS_N=$(grep -c processor /proc/cpuinfo)
declare -r IRQB_CONF_PATH="/etc/default/irqbalance"
declare -r SYSD_IRQB_PATH="/lib/systemd/system/irqbalance.service"
declare -r BAN_CONF_VAR="TFW_BAN_IRQS"
declare -a IRQS_GLOB_LIST
declare OUTPUT_TIME=false

log()
{
	local message="$1"

	if "$OUTPUT_TIME"; then
		echo "$(date '+%H:%M:%S') $message"
	else
		echo "$message"
	fi
}

calc()
{
	echo "$1" | bc -iq | tail -1
}

# Assigned IRQs can be reassigned by irqbalance. To avoid this, assigned
# vectors should be added to irqbalance config with '--banirq' option.
irqbalance_ban_irqs()
{
	args_str=""
	sysd_conf_var="ExecStart"

	for irq in ${IRQS_GLOB_LIST[@]}; do
		args_str=$args_str"--banirq=$irq "
	done

	conf_var_str="$BAN_CONF_VAR=$args_str"
	perl -i.orig -ple '
		if (/^'"$BAN_CONF_VAR"'=.*$/) {
			$_ = "'"$conf_var_str"'";
			$found = 1;
		}
		END {
			unless ($found) {
				open(CONFIG, ">>", $ARGV);
				select(CONFIG);
				print("\n# Do not edit this variable. It is"
				    . " automatically generated by start\n#"
				    . " script of Tempesta FW and is intended"
				    . " to avoid reassigning of specified"
				    . " IRQs.");
				printf("%s\n", "'"$conf_var_str"'");
				select(STDOUT);
			}
		}
	' $IRQB_CONF_PATH

	perl -i.orig -ple '
		if (/^('"$sysd_conf_var"'=.*)$/) {
			unless (/.*\$'"$BAN_CONF_VAR"'\b.*/) {
				$_ = $1 . " \$'"$BAN_CONF_VAR"'";
			}
		}
	' $SYSD_IRQB_PATH

	systemctl daemon-reload >/dev/null
	systemctl restart irqbalance.service >/dev/null
}

# This function prepares cpu mask for RSS and RPS.
# It takes into account that we can't calculate
# value, which is greater when (1 << 63) and can't
# wtite in the rps_cpus/smp_affinity value, which
# is greater then (1 << 32) -1 (we need to write it
# using comma).
make_cpu_mask()
{
	delta=$1
	mask32=$2
	val=$3
	cond=$4
	res=0

	# If delta is less than 32, we can directly calculate
	# and write this value. For RPS it will looks like
	# fff..... and for RSS it will looks like 1000....
	if [[ $delta -lt 32 ]]; then
		res=`printf %x $(( $((1 << delta )) - val))`
	else
		res="$mask32"
	fi
	delta=$(( delta - 32 ))

	# For RPS cond is 0, because (1 << delta) - val is zero
	# and we don't need to write most significat zero bits.
	while [[ $delta -ge $cond ]]
	do
		if [[ $delta -lt 32 ]]; then
			res=`printf %x $(( $((1 << delta )) - val))`",$res"
		else
			res="$mask32,$res"
		fi
		delta=$(( delta - 32 ))
	done

	echo "$res"
}

make_cpu_rss_mask()
{
	delta=$1
	# Enable only one CPU (1 << delta)
	mask32="00000000"
	# Used to calculate (1 << delta) - $val to
	# implement only one common functionfor RPS and RSS
	val=0
	cond=0

	echo `make_cpu_mask $delta $mask32 $val $cond`
}

make_cpu_rps_mask()
{
	delta=$1
	# enable all CPUs, which is less than (1 << delta) - 1
	mask32="ffffffff"
	# used to calculate (1 << delta) - $val to
	# implement only one common functionfor RPS and RSS
	val=1
	cond=1

	echo `make_cpu_mask $delta $mask32 $val $cond`
}

distribute_virtio_queues()
{
	local dev="$1" info="$2"
	local queues res bus_info irq_data irq group cpu
	local -A group_masks=()

	#virtio queues are always combined
	queues=$(ethtool -l "$dev" 2>/dev/null |
		awk '$1 == "Combined:" { print $2; exit }')
	if [[ ! $queues =~ ^[0-9]+$ ]] || (( queues < 1 )); then
		log "Combined queues for $dev not found"
		return 1
	fi

	if ! res=$(ethtool -L "$dev" combined "$queues" 2>&1); then
		log "Error: cannot set new queues count for $dev: $res"
		return 1
	fi

	bus_info=$(awk '$1 == "bus-info:" { print $2 }' <<< "$info")
	if [[ -z $bus_info ]]; then
		log "Error: cannot find bus information for $dev"
		return 1
	fi

	# Select only configured input/output queues and pair them by name.
	irq_data=$(grep -wF -- "$bus_info" /proc/interrupts |
		awk -v queues="$queues" '
			$1 ~ /^[0-9]+:$/ {
				if ($NF !~ /^virtio[0-9]+-(input|output)\.[0-9]+$/)
					next
				queue = $NF
				sub(/^.*\./, "", queue)
				if (queue + 0 >= queues)
					next
				sub(/:$/, "", $1)
				group = $NF
				sub(/-(input|output)/, "", group)
				print $1, group
			}' | sort -nu)
	if [[ -z $irq_data ]]; then
		log "Error: cannot find queue interrupts for $dev"
		return 1
	fi

	# IRQ numbers need not be contiguous or ordered by queue number.
	while read -r irq group; do
		if [[ -z ${group_masks[$group]:-} ]]; then
			cpu=$(( ${#group_masks[@]} % CPUS_N ))
			group_masks[$group]=$(make_cpu_rss_mask "$cpu")
		fi
	done <<< "$irq_data"
	if (( ${#group_masks[@]} < queues )); then
		log "Error: not enough queue interrupt groups for $dev"
		return 1
	fi

	IRQS_GLOB_LIST=()
	while read -r irq group; do
		if ! echo "${group_masks[$group]}" > "/proc/irq/$irq/smp_affinity"
		then
			log "Error: cannot set IRQ $irq affinity for $dev"
			return 1
		fi
		IRQS_GLOB_LIST+=("$irq")
	done <<< "$irq_data"
	if [ ${#IRQS_GLOB_LIST[@]} -ne 0 -a -f $SYSD_IRQB_PATH \
	     -a -f $IRQB_CONF_PATH ]; then
		systemctl status irqbalance.service >/dev/null
		[ $? -ne 0 ] || irqbalance_ban_irqs
	fi

	echo "0"
}

distribute_queues()
{
	dev=$1
	RXQ_MAX=$2
	type=$3

	# Set maximum number of available channels for better
	# packets hashing.
	res=$(ethtool -L $dev $type $RXQ_MAX 2>&1)
	if [ $? -ne 0 -a -z "$(echo $res | grep -P '^rx unmodified, ignoring')" ]
	then
		log "Error: cannot set new queues count for $dev: $res"
		return
	fi

	# Interrupts may not have interface-like description in
	# '/proc/interrupts' - so, to find the vectors we also need
	# to check the MSI directory for device.
	dev_irqs_path="/sys/class/net/$dev/device/msi_irqs"
	irqs=($(grep $dev /proc/interrupts | sed -e 's/\s*\|:.*//g'))
	if [ -z "$irqs" -a -d $dev_irqs_path ]; then
		irqs=($(ls $dev_irqs_path))
	fi

	if [ -z "$irqs" ]; then
		log "Error: cannot find interrupts for $dev"
		return
	fi

	# Skip the first IRQ since this is general async interrupt
	# for device (not assigned to any of the queues).
	irqs=(${irqs[@]:1})
	irq0=${irqs[0]}
	for i in ${irqs[@]}; do
		# Wrap around CPU mask if number of queues is
		# larger than CPUS_N.
		if [[ $(calc "$i - $irq0") -gt $CPUS_N ]]; then
			irq0=$i;
		fi
		delta=$(( i - irq0 ))
		mask=`make_cpu_rss_mask $delta`
		echo "$mask" > "/proc/irq/$i/smp_affinity"
	done

	IRQS_GLOB_LIST=(${irqs[@]})
	if [ ${#IRQS_GLOB_LIST[@]} -ne 0 -a -f $SYSD_IRQB_PATH \
	     -a -f $IRQB_CONF_PATH ]; then
		systemctl status irqbalance.service >/dev/null
		[ $? -ne 0 ] || irqbalance_ban_irqs
	fi

	echo "0"
}

distribute_rx_queues()
{
	dev=$1
	min_queues=$2
	error="Rx queues for $dev not found"

	queues_str=$(ethtool -l $dev 2>/dev/null \
		     | grep -m 1 RX | sed -e 's/RX\:\s*//')
	queues=$(printf '%d' "$queues_str" 2>/dev/null)
	if [ -n "$queues" -a ${queues:-0} -gt $min_queues ]; then
		# Switch off RPS for multi-queued interfaces.
		for rx in $TFW_NETDEV_PATH/$dev/queues/rx-*; do
			echo 0 > $rx/rps_cpus
		done

		error=`distribute_queues $dev $queues "rx"`
	fi

	echo "$error"
}

distribute_combined_queues()
{
	dev=$1
	min_queues=$2
	error="Combined queues for $dev not found"

	queues_str=$(ethtool -l $dev 2>/dev/null \
		     | grep -m 1 Combined | sed -e 's/Combined\:\s*//')
	queues=$(printf '%d' "$queues_str" 2>/dev/null)
	if [ -n "$queues" -a ${queues:-0} -gt $min_queues ]; then
		# Switch off RPS for multi-queued interfaces.
		for rx in $TFW_NETDEV_PATH/$dev/queues/rx-*; do
			echo 0 > $rx/rps_cpus
		done

		error=`distribute_queues $dev $queues "combined"`
	fi

	echo "$error"
}

# Enable RSS for networking interfaces. Enable RPS for physical devices which
# don't have enough hardware queues.
# A non-empty second argument skips enabling RPS.
tfw_set_net_queues()
{
	local info skip_rps="${2:-}"

	devs=$1
	min_queues=$(calc "$CPUS_N / 2")
	cpu_mask=`make_cpu_rps_mask $CPUS_N`

	# Configure virtio IRQs separately from physical-device RSS/RPS.
	for dev in $devs; do
		info=$(ethtool -i "$dev" 2>/dev/null)
		if [[ $(awk '$1 == "driver:" { print $2 }' <<< "$info") == virtio_net ]]
		then
			log "...distribute $dev virtio queues"
			error=$(distribute_virtio_queues "$dev" "$info")
			if [[ "$error" != "0" ]]; then
				log "$error"
			fi
			continue
		fi
		log "...distribute $dev rx queues"
		# First try to setup RX queues.
		error=`distribute_rx_queues $dev $min_queues`
		if [[ "$error" != "0" ]]; then
			log "$error"
			log "...distribute $dev combined queues"
			# If RX queues setup fails try to setup
			# combined queues.
			error=`distribute_combined_queues $dev $min_queues`
		fi
		if [[ "$error" != "0" ]]; then
			log "$error"
			if [[ -n $skip_rps ]]; then
				continue
			fi
			log "...enable RPS on $dev"
			for rx_queue in $TFW_NETDEV_PATH/$dev/queues/rx-*
			do
				echo $cpu_mask > $rx_queue/rps_cpus
			done
		fi
	done
}

tfw_irqbalance_revert()
{
	if systemctl -q is-active irqbalance.service 2>/dev/null && [ -f $IRQB_CONF_PATH ]; then
		log "...revert irqbalance config"
		perl -i.orig -ple '
			s/^('"$BAN_CONF_VAR"'=).*$/$1/;
		' $IRQB_CONF_PATH
		systemctl restart irqbalance.service >/dev/null 2>&1 || true
	fi
}

usage()
{
	printf 'Usage: %s [--no-rps] [--output-time] DEVICE [DEVICE ...]\n' "$0"
	printf '       %s [--output-time] --revert\n' "$0"
}

set_irq_affinity_main()
{
	local skip_rps="" revert=false

	while [[ $# -gt 0 ]]; do
		case "$1" in
		--no-rps) skip_rps=1 ;;
		--output-time) OUTPUT_TIME=true ;;
		--revert) revert=true ;;
		-h|--help) usage; return 0 ;;
		--) shift; break ;;
		-*) usage >&2; return 1 ;;
		*) break ;;
		esac
		shift
	done

	if "$revert"; then
		if [[ $# -ne 0 || -n $skip_rps ]]; then
			usage >&2
			return 1
		fi
		tfw_irqbalance_revert
	else
		if [[ $# -eq 0 || -z $* ]]; then
			usage >&2
			return 1
		fi
		if ! hash bc &> /dev/null; then
			log "'bc' command not found"
			return 1
		fi
		tfw_set_net_queues "$*" "$skip_rps"
	fi
}

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
	set_irq_affinity_main "$@"
fi
